import * as fs from "node:fs";
import * as path from "node:path";
import * as url from "node:url";

import { datasetFileName, findDatasetDirectory } from "../src/data/locate-dataset.ts";

/**
 * The part of the dataset this script reads.
 */
type DatasetMetadataOnly = {
    /**
     * Release metadata of the dataset.
     */
    _metadata: DatasetVersionMetadata;
};

/**
 * Version fields of the dataset's metadata block.
 */
type DatasetVersionMetadata = {
    /**
     * Semantic version of the output schema.
     */
    schema_version: string;
};

const scriptDirectory = path.dirname(url.fileURLToPath(import.meta.url));
const rootDirectory = path.join(scriptDirectory, "..");
const bindingsDirectory = path.join(rootDirectory, "src", "data", "bindings");
const datasetDirectory = findDatasetDirectory(rootDirectory, process.env.OPEN_PALEO_DATA);

// Copy the generated TypeScript bindings unchanged.
fs.copyFileSync(
    path.join(datasetDirectory, "bindings", "open-paleo.d.ts"),
    path.join(bindingsDirectory, "open-paleo.d.ts"),
);

// Record the schema version the bindings describe, so the build can refuse an incompatible
// dataset.
const dataset = JSON.parse(fs.readFileSync(path.join(datasetDirectory, datasetFileName), "utf8")) as DatasetMetadataOnly;
const schemaVersion = dataset._metadata.schema_version;

fs.writeFileSync(
    path.join(bindingsDirectory, "schema-version.ts"),
    "// Generated by npm run update-bindings. Do not edit by hand.\n\n" +
    "/**\n * Output schema version that open-paleo.d.ts describes.\n */\n" +
    "export const bindingsSchemaVersion = \"" + schemaVersion + "\";\n",
);

console.log("Copied bindings for schema " + schemaVersion + " from " + datasetDirectory);
